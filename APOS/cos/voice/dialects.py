def google_lang_list() -> list[str]:
    raw = (os.getenv("COS_STT_GOOGLE_LANGS") or DEFAULT_GOOGLE_LANGS).strip()
    langs = [x.strip() for x in raw.replace("\n", ",").split(",") if x.strip()]
    # تأكيد وجود العراقية والفصحى في المقدمة
    preferred = ["ar-IQ", "ar-SA"]
    out: list[str] = []
    for p in preferred:
        if p not in out:
            out.append(p)
    for x in langs:
        if x not in out:
            out.append(x)
    return out


def normalize_dialect(text: str) -> str:
    """حوّل تعابير لهجية شائعة (خصوصاً العراقية) إلى فصحى أقرب للتوجيه."""
    t = (text or "").strip()
    if not t:
        return t
    out = t
    for pat, repl in _IRAQI_TO_MSA:
        out = re.sub(pat, repl, out, flags=re.IGNORECASE)
    return " ".join(out.split())


